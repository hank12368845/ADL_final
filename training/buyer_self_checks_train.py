from contextlib import nullcontext
import json
import math
import os
from pathlib import Path
import random
import time

ROOT = Path(__file__).resolve().parents[1]


def summarize(rows):
    from training.buyer_self_checks import summarize as fields_summary
    from training.buyer_latest_brakes_train import summary as tool_summary
    checks = {}
    for suite in ('self_check_seen', 'self_check_validation'):
        selected = [r for r in rows if r['suite'] == suite]
        checks[suite] = fields_summary(selected)
        checks[suite]['personas'] = {str(p): fields_summary([r for r in selected if r['persona_index'] == p]) for p in (1, 2, 3)}
        checks[suite]['channels'] = {c: fields_summary([r for r in selected if r['channel'] == c]) for c in ('board', 'offer')}
    checks['regression'] = {k: v for k, v in tool_summary(rows).items() if k in ('current', 'official')}
    return checks


def gates(parent, current):
    seen = current['self_check_seen']; val = current['self_check_validation']
    old = current['regression']; prior = parent['regression']
    return dict(
        seen_all_fields_exact=seen['all_fields_exact'] == seen['calls'],
        validation_target_fields_exact=all(val['target_fields'][f] == val['calls'] for f in val['target_fields']),
        validation_all_candidates_at_least_22=val['all_fields_exact'] >= 22,
        retain_positive_capture=all(s['captured'] == s['positive_total'] for s in (seen, val)),
        safe_negative_decisions=all(s['negative_safe'] == s['negative_total'] for s in (seen, val)),
        retain_known_fresh=all(old['current'][k] >= prior['current'][k] for k in ('known_captured', 'fresh_captured')),
        retain_official=old['official']['valid'] >= prior['official']['valid'],
        no_new_cash_or_owned_regression=all(old[k][f] <= prior[k][f] for k in old for f in ('cash_errors', 'owned_errors')),
        no_missing_tool_or_truncation=all(s['no_tool'] == 0 and s['truncated'] == 0 for s in (seen, val, *old.values())))


def write_review(folder):
    folder = Path(folder); results = [json.loads(p.read_text()) for p in sorted(folder.glob('native_step_*.json'))]
    lines = ['# Buyer autonomous self-check pilot', '',
        'All scratchpads below were generated by the model from the unchanged latest prompt. No facts/verdict prefix was supplied.',
        'Fields are integer cents / booleans. Missing, malformed, wrong-ID and omitted candidates count as incorrect. This schema is not an engine rule.',
        'The parent was not trained on this output schema: a missing structured field is not proof its earlier natural-language calculation was wrong. Read format/coverage alongside field accuracy.',
        '48 distinct training cases, two passes, 12 steps; seen tests measure learnability, held-out controls measure this narrow transfer, neither is a market grade.', '',
        '| Step | Split | JSON format | Candidate coverage | Exact entire scratchpad | Cash | Total | Held | Current next value | Adjusted value | Affordable | Eligible | Positive capture | Negative safe |',
        '|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
    for result in results:
        for split in ('self_check_seen', 'self_check_validation'):
            s = result['summary'][split]; n = s['calls']; f = s['target_fields']
            fields = ' | '.join(f'{f[k]}/{n}' for k in ('cash', 'total', 'held', 'next_value', 'adjusted_value', 'affordable', 'eligible'))
            lines.append(f'| {result["step"]} | {split} | {s["format_valid"]}/{n} | {s["coverage"]}/{n} | {s["all_fields_exact"]}/{n} | {fields} | {s["captured"]}/{s["positive_total"]} | {s["negative_safe"]}/{s["negative_total"]} |')
    lines += ['', 'Field columns show the actual target candidate to avoid hiding errors behind easy distractors. Entire-scratchpad accuracy also requires every live candidate. Raw JSON includes all-candidate denominators, each persona/channel, paired flips, and tool validity conditional on exact fields.', '',
        '| Step | Current capture /14 | Current cash / owned | Official valid /9 |', '|---:|---:|---:|---:|']
    for result in results:
        s = result['summary']['regression']; c = s['current']; o = s['official']
        lines.append(f'| {result["step"]} | {c["captured"]} | {c["cash_errors"]} / {c["owned_errors"]} | {o["valid"]} |')
    if results:
        latest = results[-1]
        lines += ['', f'## Latest checkpoint ({latest["step"]}): persona / channel breakdown', '',
            '| Split | Group | Cash | Total | Held | Next value | Eligible | Entire scratchpad | Positive capture |',
            '|---|---|---:|---:|---:|---:|---:|---:|---:|']
        for split in ('self_check_seen', 'self_check_validation'):
            summary = latest['summary'][split]
            for dimension in ('personas', 'channels'):
                for label, s in summary[dimension].items():
                    f = s['target_fields']; n = s['calls']
                    values = ' | '.join(f'{f[k]}/{n}' for k in ('cash', 'total', 'held', 'next_value', 'eligible'))
                    lines.append(f'| {split} | {dimension}:{label} | {values} | {s["all_fields_exact"]}/{n} | {s["captured"]}/{s["positive_total"]} |')
    if (folder/'finished.json').exists():
        lines += ['', '```json', (folder/'finished.json').read_text().strip(), '```']
    lines += ['', 'Field-first success is necessary evidence for this intervention, not proof all future tools will be correct. No automatic checkpoint promotion, extended training or market evaluation.']
    (folder/'self_check_review.md').write_text('\n'.join(lines)+'\n')


def worker(folder):
    import torch
    import torch.distributed as dist
    from torch.nn.parallel import DistributedDataParallel as DDP
    from transformers import AutoModelForCausalLM, AutoTokenizer
    from tqdm import tqdm
    from training.buyer_self_checks_data import check_data
    from training.buyer_self_checks import FIELDS, losses, score
    from training.buyer_latest_brakes_data import sha
    from training.buyer_operations_train import adapter_model, save_adapter
    from training.reasoning_checkpoint import load_weights, save_state
    from training.official_buyer_train import preflight_training_mode, generation_stop_ids
    from training.step84_repair_plan import assess
    from training.decision_ablation import fingerprint
    folder = Path(folder); cfg = json.loads((folder/'train_config.json').read_text())
    for name, digest in cfg['training_sources'].items():
        if sha(ROOT/name) != digest: raise ValueError(f'Launch source changed: {name}')
    if sha(ROOT/cfg['data_dir']/'manifest.json') != cfg['data_manifest_sha256']:
        raise ValueError('Launch manifest changed')
    rank = int(os.environ['RANK']); local = int(os.environ['LOCAL_RANK']); device = torch.device('cuda', local)
    if int(os.environ['WORLD_SIZE']) != 2: raise ValueError('Exactly two ranks required')
    torch.cuda.set_device(local); torch.cuda.set_per_process_memory_fraction(cfg['devices'][local]['fraction'], local)
    dist.init_process_group('nccl', device_id=device); torch.manual_seed(cfg['seed']); random.seed(cfg['seed'])
    train, val, batches, manifest = check_data(cfg)
    print(f'[rank{rank}] Loading bf16 base + fixed official step84; fresh field-first optimizer; ETA estimating.', flush=True)
    base, info = AutoModelForCausalLM.from_pretrained(cfg['base_model'], revision=cfg['revision'], local_files_only=True,
        dtype=torch.bfloat16, device_map={'': device}, attn_implementation='sdpa', output_loading_info=True)
    if info.get('missing_keys') or info.get('mismatched_keys'): raise ValueError('Incomplete base model')
    base.config.use_cache = False; model = adapter_model(base, cfg); load_weights(model, manifest['parent_adapter'])
    model.gradient_checkpointing_enable(gradient_checkpointing_kwargs={'use_reentrant': False}); model.enable_input_require_grads()
    tokenizer = AutoTokenizer.from_pretrained(cfg['base_model'], revision=cfg['revision'], local_files_only=True)
    eos = generation_stop_ids(model, tokenizer)
    optimizer = torch.optim.AdamW([p for p in model.parameters() if p.requires_grad], lr=cfg['learning_rate'], weight_decay=.01)
    def rate(step):
        return (step+1)/2 if step < 2 else .5*(1+math.cos(math.pi*min(1., (step-2)/10)))
    scheduler = torch.optim.lr_scheduler.LambdaLR(optimizer, rate)
    cases = json.loads((ROOT/cfg['data_dir']/'evaluation_cases.json').read_text())
    (folder/f'hardware_rank{rank}.json').write_text(json.dumps(dict(rank=rank, physical_gpu=cfg['devices'][local]['index'],
        name=torch.cuda.get_device_name(local), startup_budget_gib=cfg['devices'][local]['budget_gib'])))

    def evaluate(step):
        model.eval(); rows = []; nll = []
        with torch.inference_mode():
            for i in tqdm(list(range(len(val)))[rank::2], desc=f'rank{rank} field NLL step{step}', position=rank, unit='cases'):
                with torch.autocast('cuda', dtype=torch.bfloat16):
                    result = losses(model, val[i], device)
                nll.append({k: v.item() for k, v in result.items()})
            jobs = [c for c in cases if c['evaluation_rank'] == rank]
            for c in tqdm(jobs, desc=f'rank{rank} autonomous checks step{step}', position=rank, unit='cases'):
                cached = c.get('cached_parent') if step == 0 else None
                if cached:
                    raw = cached['text']; truncated = cached['truncated']
                else:
                    # No answer, target, oracle or output schema is appended to the prompt.
                    prompt = tokenizer.apply_chat_template(c['messages'], tools=c['tools'], tokenize=False,
                        add_generation_prompt=True, enable_thinking=True)
                    ids = tokenizer(prompt, add_special_tokens=False, return_tensors='pt').to(device)
                    with torch.autocast('cuda', dtype=torch.bfloat16):
                        out = model.generate(**ids, max_new_tokens=1024, do_sample=False, use_cache=True,
                            eos_token_id=eos, pad_token_id=tokenizer.pad_token_id, return_dict_in_generate=False)
                    tail = out[0, ids.input_ids.shape[1]:]; raw = tokenizer.decode(tail, skip_special_tokens=False)
                    truncated = len(tail) >= 1024 and int(tail[-1]) not in eos
                r = assess(c, 'latest', raw, tokenizer, truncated, rank, bool(cached)); r['persona_index'] = c['persona_index']
                if c['suite'].startswith('self_check_'):
                    r['self_check'] = score(c, raw)
                rows.append(r)
        gathered = [None, None]; dist.all_gather_object(gathered, dict(rows=rows, nll=nll))
        rows = [r for p in gathered for r in p['rows']]; nll = [n for p in gathered for n in p['nll']]
        if len(rows) != 73 or len({r['case'] for r in rows}) != 73: raise ValueError('Missing/repeated evaluation')
        result = dict(step=step, summary=summarize(rows),
            teacher_forced_nll={k: sum(r[k] for r in nll)/len(nll) for k in nll[0]}, decisions=rows)
        if rank == 0:
            (folder/f'native_step_{step:04d}.json').write_text(json.dumps(result, indent=2)+'\n'); write_review(folder)
            print(f'Step{step} autonomous fields: seen {result["summary"]["self_check_seen"]["all_fields_exact"]}/12; held-out {result["summary"]["self_check_validation"]["all_fields_exact"]}/24', flush=True)
        model.train(); return result

    layers = preflight_training_mode(model)
    print(f'[rank{rank}] Memory preflight in train mode, {layers} checkpointed layers; ETA estimating.', flush=True)
    rng = (torch.get_rng_state(), torch.cuda.get_rng_state(device))
    indices = {max(range(len(train)), key=lambda i: len(train[i]['input_ids'])), max(range(len(train)), key=lambda i: train[i]['target_length'])}
    for i in indices:
        with torch.autocast('cuda', dtype=torch.bfloat16): loss = losses(model, train[i], device)['total']
        loss.backward(); model.zero_grad(set_to_none=True); del loss
    torch.set_rng_state(rng[0]); torch.cuda.set_rng_state(rng[1], device); dist.barrier()
    baseline = evaluate(0)['summary']; wrapped = DDP(model, device_ids=[local], broadcast_buffers=False)
    began = time.monotonic(); status = 'complete'; scores = []
    loss_keys = ('total', 'fields', 'completion', *('field_'+f for f in FIELDS))
    with (folder/f'samples_rank{rank}.jsonl').open('w') as trace, (folder/f'metrics_rank{rank}.jsonl').open('w') as metrics:
        bar = tqdm(range(1, 13), total=12, desc='Field-first pilot', unit='steps', disable=rank != 0)
        for step in bar:
            optimizer.zero_grad(set_to_none=True); sums = torch.zeros(len(loss_keys), device=device)
            for micro, i in enumerate(batches[step-1][rank::2]):
                row = train[i]; trace.write(json.dumps(dict(step=step, rank=rank, micro=micro, id=row['id'], label_action=row['label_action']))+'\n'); trace.flush()
                if rank == 0: bar.set_description(f'Field-first {step}/12 micro{micro+1}/4')
                with wrapped.no_sync() if micro < 3 else nullcontext():
                    with torch.autocast('cuda', dtype=torch.bfloat16): result = losses(wrapped, row, device)
                    if not torch.isfinite(result['total']): raise ValueError('Nonfinite training loss')
                    (result['total']/4).backward()
                sums += torch.stack([result[k].detach() for k in loss_keys])/4
            torch.nn.utils.clip_grad_norm_([p for p in model.parameters() if p.requires_grad], 1., error_if_nonfinite=True)
            lr = optimizer.param_groups[0]['lr']; optimizer.step(); scheduler.step(); dist.all_reduce(sums)
            record = dict(step=step, loss=dict(zip(loss_keys, (sums/2).tolist())), lr=lr, elapsed_seconds=time.monotonic()-began,
                peak_gpu_gib=torch.cuda.max_memory_allocated(device)/2**30)
            metrics.write(json.dumps(record)+'\n'); metrics.flush()
            if rank == 0: bar.set_postfix(fields=f'{record["loss"]["fields"]:.3f}', exposures=f'{step*8}/96')
            if step in (6, 12):
                cp = folder/'checkpoints'/f'step_{step:04d}'
                if rank == 0: save_adapter(model, cp, cfg, step)
                dist.barrier(); result = evaluate(step); check = gates(baseline, result['summary'])
                save_state(cp, model, optimizer, scheduler, step, rank, device); dist.barrier()
                scores.append(dict(step=step, gates=check))
                if rank == 0:
                    (cp/'checkpoint_complete.json').write_text(json.dumps(dict(step=step, adapter_fingerprints=fingerprint(cp))))
                    (folder/'checkpoint_scores.json').write_text(json.dumps(scores, indent=2)+'\n')
                if result['summary']['regression']['current']['captured'] < baseline['regression']['current']['captured']-2:
                    status = 'stopped_recall_regression'; break
    if rank == 0:
        (folder/'finished.json').write_text(json.dumps(dict(status=status, step=step,
            field_and_tool_gate_passed_steps=[r['step'] for r in scores if all(r['gates'].values())],
            development_candidate=None, note='No promotion. First inspect autonomous per-field learning and persona/channel regressions before deciding further work.',
            training_and_checkpoint_eval_seconds=time.monotonic()-began), indent=2)+'\n'); write_review(folder)
    dist.barrier(); dist.destroy_process_group()


if __name__ == '__main__':
    import argparse
    import sys
    sys.path.insert(0, str(ROOT))
    p = argparse.ArgumentParser(); p.add_argument('--session', type=Path, required=True)
    worker(p.parse_args().session)
